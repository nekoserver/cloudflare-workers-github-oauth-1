export type HeritageItem = { n: string; e: string; y: number; [key: string]: unknown };

export function buildCountryHeritageCitiesHtml(
  matches: HeritageItem[],
  cityCounts: Record<string, number>,
  uniqueTotal: number,
): string {
  const sorted = matches.slice().sort((a, b) => b.y - a.y);
  let html = '';
  for (const d of sorted) {
    const count = cityCounts[d.n];
    const countStr = count != null ? String(count) : '-';
    html += '<div class="ch-item ch-item-cities" data-name="' + d.n + '">' +
      '<span class="ch-item-emoji">' + d.e + '</span>' +
      '<span class="ch-item-name">' + d.n + '</span>' +
      '<span class="ch-item-year">' + d.y + '年</span>' +
      '<span class="ch-item-citycount">' + countStr + '</span>' +
      '</div>';
  }
  html += '<div class="ch-item ch-item-total">' +
    '<span class="ch-item-total-label">合計（重複なし都市数）</span>' +
    '<span class="ch-item-citycount ch-item-total-count">' + uniqueTotal + '</span>' +
    '</div>';
  return html;
}
